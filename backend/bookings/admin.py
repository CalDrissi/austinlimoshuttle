    extra = 0
    fields = ["created_at", "event_type", "driver", "latitude", "longitude",
              "location_accuracy"]
    readonly_fields = fields
    can_delete = False
    ordering = ["created_at"]
    verbose_name_plural = "Driver trip events (live status pings)"

