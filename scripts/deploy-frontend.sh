#!/usr/bin/env bash
#
# Gate-free frontend fast-deploy (host Next.js under pm2).
#
# The Next.js storefront no longer runs in Docker — it runs on the host via
# pm2 under the unprivileged `limoweb` user (see ecosystem.config.js). This
# script does a BUILD-BEFORE-RESTART deploy so the live pm2 process keeps
# serving the old build until the new one is compiled; only a successful
# build triggers the reload.
#
#   ssh root@<vps>  'bash /opt/austinlimoshuttle/scripts/deploy-frontend.sh'
#
# Runs as root, but root only pulls and reads .env: the npm ci, next build,
# and pm2 reload all run as limoweb (the repo checkout is root-owned; only
# frontend/ is chowned to limoweb so it can write node_modules/.next).
#
# Backend + DB stay in Docker and go through the normal merge gate; this path
# is for frontend-only changes and is intentionally gate-free.
set -euo pipefail

APP_DIR=/opt/austinlimoshuttle
cd "$APP_DIR"

git pull origin main

# The pull runs as root, so any files it created/updated inside frontend/ are
# root-owned — hand them back to limoweb or the build can't rewrite them
# (e.g. next-env.d.ts is regenerated by `next build`).
chown -R limoweb:limoweb "$APP_DIR/frontend"

# CRITICAL: NEXT_PUBLIC_* are inlined into the client bundle at BUILD time, so
# the host build MUST use the exact same values the Docker build used, sourced
# from the single source of truth (the git-ignored root .env, readable only by
# root — which is why root extracts them and passes them into the limoweb
# environment below). If they are wrong/missing the site silently points at
# the wrong API, so we fail loudly.
NEXT_PUBLIC_API_BASE_URL="$(grep -E '^NEXT_PUBLIC_API_BASE_URL=' .env | cut -d= -f2- || true)"
NEXT_PUBLIC_USE_MOCKS="$(grep -E '^NEXT_PUBLIC_USE_MOCKS=' .env | cut -d= -f2- || true)"
: "${NEXT_PUBLIC_API_BASE_URL:?NEXT_PUBLIC_API_BASE_URL missing from $APP_DIR/.env}"
NEXT_PUBLIC_USE_MOCKS="${NEXT_PUBLIC_USE_MOCKS:-false}"

su - limoweb -c "cd '$APP_DIR/frontend' \
  && export NEXT_PUBLIC_API_BASE_URL='$NEXT_PUBLIC_API_BASE_URL' \
            NEXT_PUBLIC_USE_MOCKS='$NEXT_PUBLIC_USE_MOCKS' \
            NEXT_TELEMETRY_DISABLED=1 \
  && npm ci --prefer-offline \
  && npm run build"

# Build succeeded — swap the limoweb pm2 process over to the new build, using
# the repo ecosystem config as the single source of truth for the app spec
# (localhost bind, port, env).
su - limoweb -c "pm2 startOrReload '$APP_DIR/ecosystem.config.js' --update-env && pm2 save"

echo "deploy-frontend: limo-frontend reloaded on the new build (user: limoweb)."
